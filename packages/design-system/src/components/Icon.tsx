export interface IconProps {
  /** Canonical name (e.g. "clock") or an SF Symbol name (e.g. "clock.fill"). */
  name: IconName | string
  /** Height in px (width scales with the glyph's aspect ratio). Default 20. */
  size?: number
  /** Color; defaults to currentColor. */
  color?: string
  /** Stroke width for line icons. Default 2. */
  strokeWidth?: number
  className?: string
  style?: CSSProperties
}

/** Resolve an SF Symbol or canonical name to an icon definition. */
export function resolveIconName(name: string): IconName | undefined {
  if (name in ICONS) return name as IconName
  return SF_ALIASES[name]
}

/**
 * Vector icon set: custom glyphs use traced path data; generic glyphs are drawn on a 24x24 grid. Color inherits
 * from text color unless `color` is set.
 */
export function Icon({ name, size = 20, color, strokeWidth = 2, className, style }: IconProps) {
  const key = resolveIconName(String(name))
  const def = key ? ICONS[key] : undefined
  if (!def) return null
  const viewBox = def.viewBox ?? "0 0 24 24"
  const [, , vw, vh] = viewBox.split(" ").map(Number)
  const width = Math.round(size * (vw / vh) * 100) / 100
  return (
    <svg
      viewBox={viewBox}
      width={width}
      height={size}
      fill={def.stroke ? "none" : "currentColor"}
      stroke={def.stroke ? "currentColor" : "none"}
      strokeWidth={def.stroke ? strokeWidth : undefined}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={color ? { color, ...style } : style}
      aria-hidden
    >
      {def.content}
    </svg>
  )
}
