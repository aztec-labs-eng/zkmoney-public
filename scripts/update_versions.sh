#!/usr/bin/env bash
set -e

# Simple script to update the version of the Aztec packages in the repo.
# Update the versions in the package.json, the old and new so it knows what to update.
# This will have to change when we get to 1.0.0, it may start changing things it shouldnt.

# -----------------------------
# Usage:
#    scripts/update_versions.sh <oldVersion> <newVersion>

#. Make sure t0 run this first.
#chmod +x scripts/update_versions.sh

#
# This updates:
#  1) Nargo.toml lines like:   tag = 'aztec-packages-v0.67.0' --> tag = 'aztec-packages-v0.68.0'
#  2) package.json references: "@aztec/foo": "0.67.0"        --> "@aztec/foo": "0.68.0"
# -----------------------------

USAGE="Usage: $0 --oldVersion <X> --newVersion <Y>"

OLD_VERSION=""
NEW_VERSION=""

# --- Parse arguments ---
while [[ $# -gt 0 ]]; do
  case "$1" in
    --oldVersion)
      OLD_VERSION="$2"
      shift 2
      ;;
    --newVersion)
      NEW_VERSION="$2"
      shift 2
      ;;
    *)
      echo "Unknown argument: $1"
      echo "$USAGE"
      exit 1
      ;;
  esac
done

# Validate required args
if [ -z "$OLD_VERSION" ] || [ -z "$NEW_VERSION" ]; then
  echo "$USAGE"
  exit 1
fi

echo "=================================================="
echo "Updating from $OLD_VERSION to $NEW_VERSION ..."
echo "=================================================="

# -----------------------------------------
# 1) Update Nargo.toml tags
# -----------------------------------------

echo "Updating Nargo.toml files..."

# Find all Nargo.toml under packages/contracts.
for toml_file in $(find packages/contracts -type f -name 'Nargo.toml' -not -path '*/node_modules/*' -not -path '*/.git/*'); do
  echo " -> Updating $toml_file"

  # Replace '0.67.0' with '0.68.0'
  sed -i.bak -E "s|$OLD_VERSION|$NEW_VERSION|g" "$toml_file"

  # Remove the backup file generated by sed (macOS behavior)
  rm -f "$toml_file.bak"
done

echo "Nargo.toml updates complete."
echo ""

# -----------------------------------------
# 2) Update package.json Aztec dependencies
# -----------------------------------------

echo "Updating package.json files..."

# Skips: vendor/ (the oxide submodule carries its own Aztec pin and is moved by gitlink, not sed)
# and .claude/ (live git worktrees — rewriting them silently edits unrelated branches).
for json_file in $(find . -type f -name 'package.json' -not -path '*/node_modules/*' -not -path '*/.git/*' -not -path './vendor/*' -not -path './.claude/*'); do
  echo " -> Updating $json_file"

  # Use double quotes to allow variable expansion and properly escape the pattern
  sed -i.bak -E "/\"@nemi-fi\/wallet-sdk\"/! s|\"$OLD_VERSION\"|\"$NEW_VERSION\"|g" "$json_file"

  rm -f "$json_file.bak"
done

echo "package.json updates complete."
echo ""

# The frozen refund runtime refuses a source node on another Aztec release.
sed -i.bak -E "s|\"$OLD_VERSION\"|\"$NEW_VERSION\"|g" packages/sdk/src/services/FrozenRefundMigrationRuntime.ts
rm -f packages/sdk/src/services/FrozenRefundMigrationRuntime.ts.bak

echo "All done!"

